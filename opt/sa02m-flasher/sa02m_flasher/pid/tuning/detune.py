# -*- coding: utf-8 -*-
"""
Ослабление/усиление настроек относительно базовых (АВАДС САР-эксперт: операции
«Ослабить»/«Усилить»/«У+»).

Базовые настройки (Kc, Ti) рассчитываются по критерию минимального времени
регулирования. Оператор может итеративно ослаблять их для повышения запаса
устойчивости; усиление возвращает настройки в сторону базовых, но не сильнее
базовых (level ≤ 0). Каждый шаг — множитель DETUNE_FACTOR по Kc и Ti.

«У+» (add_derivative_for_stability) — добавить небольшую Д-часть по критерию
увеличения устойчивости к ПИ-настройке (позволяет либо ускорить контур при том
же запасе, либо повысить запас при той же скорости).
"""
from __future__ import annotations

from typing import Tuple

DETUNE_FACTOR = 1.3   # множитель Kc/Ti за один шаг ослабления/усиления


def detuned(base_kc: float, base_ti_s: float, level: int) -> Tuple[float, float]:
    """
    Настройки на заданном уровне относительно базовых.

    level = 0 — базовые; level < 0 — ослабленные |level| раз (меньше Kc, больше
    Ti). level > 0 не имеет смысла (сильнее базовых) и приводится к 0.
    """
    lvl = min(0, int(level))
    f = DETUNE_FACTOR ** (-lvl)     # -lvl ≥ 0 → f ≥ 1
    kc = base_kc / f
    ti = base_ti_s * f
    return kc, ti


def add_derivative_for_stability(L_eff: float, ti_s: float,
                                 fraction_of_delay: float = 0.4) -> float:
    """
    Рекомендуемая Тд для повышения запаса устойчивости ПИ-настройки («У+»).

    Дифференцирование добавляет опережение по фазе; берётся консервативная доля
    запаздывания, ограниченная сверху четвертью Ti (чтобы Д-часть не доминировала).
    """
    td = max(0.0, fraction_of_delay * max(L_eff, 0.0))
    return min(td, 0.25 * max(ti_s, 0.0))
